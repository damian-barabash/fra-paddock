-- Role: admin | client. Treści: wpisy, zaproszenia, oferty imienne, pop-upy.
-- Dane z Fastline Performance Lab (litry, historia) trzymamy jako kopię w fpl_snapshots.

-- ───────── Profile i role ─────────
do $$ begin
  create type public.member_role as enum ('admin', 'client');
exception when duplicate_object then null; end $$;

create table if not exists public.profiles (
  id              uuid primary key references auth.users (id) on delete cascade,
  role            public.member_role not null default 'client',
  email           text not null,
  full_name       text not null default '',
  phone           text,
  member_no       integer generated by default as identity unique,
  member_since    date not null default current_date,
  fpl_email       text,              -- e-mail konta w Performance Lab (puste = ten sam co login)
  welcome_seen_at timestamptz,       -- pierwsze wejście: prezentacja Klubu
  disabled        boolean not null default false,
  created_by      uuid references auth.users (id) on delete set null,
  created_at      timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin' and not disabled)
$$;

create or replace function public.is_member()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and not disabled)
$$;

alter table public.profiles enable row level security;
drop policy if exists "own profile or admin" on public.profiles;
create policy "own profile or admin" on public.profiles
  for select to authenticated using (id = auth.uid() or public.is_admin());
drop policy if exists "admin updates profiles" on public.profiles;
create policy "admin updates profiles" on public.profiles
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
-- insert / delete: tylko funkcja admin-users (service_role)

-- ───────── Wpisy: aktualności, zaproszenia, oferty imienne ─────────
do $$ begin
  create type public.post_kind as enum ('post', 'invitation', 'offer');
exception when duplicate_object then null; end $$;

create table if not exists public.posts (
  id            uuid primary key default gen_random_uuid(),
  kind          public.post_kind not null default 'post',
  title         text not null,
  lead          text,
  body_html     text not null default '',
  cover_url     text,
  audience      text not null default 'all' check (audience in ('all', 'selected')),
  -- zaproszenie
  event_at      timestamptz,
  event_end_at  timestamptz,
  event_place   text,
  rsvp_until    timestamptz,
  dress_code    text,
  -- oferta
  valid_until   timestamptz,
  cta_label     text,
  cta_url       text,
  --
  published     boolean not null default true,
  pinned        boolean not null default false,
  published_at  timestamptz not null default now(),
  created_by    uuid references auth.users (id) on delete set null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists posts_feed_idx on public.posts (published_at desc);

create table if not exists public.post_recipients (
  post_id uuid not null references public.posts (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  primary key (post_id, user_id)
);
create index if not exists post_recipients_user_idx on public.post_recipients (user_id);

create or replace function public.can_see_post(p_post uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select public.is_admin() or exists (
    select 1 from public.posts p
    where p.id = p_post and p.published and p.published_at <= now() and public.is_member()
      and (p.audience = 'all'
           or exists (select 1 from public.post_recipients r where r.post_id = p.id and r.user_id = auth.uid()))
  )
$$;

alter table public.posts enable row level security;
drop policy if exists "members read visible posts" on public.posts;
create policy "members read visible posts" on public.posts
  for select to authenticated using (public.can_see_post(id));
drop policy if exists "admin writes posts" on public.posts;
create policy "admin writes posts" on public.posts
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

alter table public.post_recipients enable row level security;
drop policy if exists "own recipient rows" on public.post_recipients;
create policy "own recipient rows" on public.post_recipients
  for select to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists "admin writes recipients" on public.post_recipients;
create policy "admin writes recipients" on public.post_recipients
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- ───────── Odpowiedzi na zaproszenia ─────────
create table if not exists public.rsvps (
  post_id      uuid not null references public.posts (id) on delete cascade,
  user_id      uuid not null references public.profiles (id) on delete cascade,
  status       text not null check (status in ('yes', 'no')),
  note         text,
  responded_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

alter table public.rsvps enable row level security;
drop policy if exists "read own rsvp or admin" on public.rsvps;
create policy "read own rsvp or admin" on public.rsvps
  for select to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists "answer own invitation" on public.rsvps;
create policy "answer own invitation" on public.rsvps
  for insert to authenticated with check (user_id = auth.uid() and public.can_see_post(post_id));
drop policy if exists "change own answer" on public.rsvps;
create policy "change own answer" on public.rsvps
  for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid() and public.can_see_post(post_id));

-- ───────── Pop-upy od administratora ─────────
create table if not exists public.popups (
  id         uuid primary key default gen_random_uuid(),
  title      text not null,
  body_html  text not null default '',
  image_url  text,
  cta_label  text,
  cta_url    text,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);
create table if not exists public.popup_recipients (
  popup_id uuid not null references public.popups (id) on delete cascade,
  user_id  uuid not null references public.profiles (id) on delete cascade,
  seen_at  timestamptz,
  primary key (popup_id, user_id)
);

alter table public.popups enable row level security;
drop policy if exists "recipients read popups" on public.popups;
create policy "recipients read popups" on public.popups
  for select to authenticated using (
    public.is_admin()
    or exists (select 1 from public.popup_recipients r where r.popup_id = id and r.user_id = auth.uid())
  );
drop policy if exists "admin writes popups" on public.popups;
create policy "admin writes popups" on public.popups
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

alter table public.popup_recipients enable row level security;
drop policy if exists "own popup rows" on public.popup_recipients;
create policy "own popup rows" on public.popup_recipients
  for select to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists "admin writes popup rows" on public.popup_recipients;
create policy "admin writes popup rows" on public.popup_recipients
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

