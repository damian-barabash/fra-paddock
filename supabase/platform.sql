-- ───────── Akcje klienta ─────────
create or replace function public.mark_welcome_seen()
returns void language sql security definer set search_path = public as $$
  update public.profiles set welcome_seen_at = coalesce(welcome_seen_at, now()) where id = auth.uid()
$$;

create or replace function public.mark_popup_seen(p_popup uuid)
returns void language sql security definer set search_path = public as $$
  update public.popup_recipients set seen_at = coalesce(seen_at, now())
  where popup_id = p_popup and user_id = auth.uid()
$$;

revoke all on function public.mark_welcome_seen() from public, anon;
revoke all on function public.mark_popup_seen(uuid) from public, anon;
grant execute on function public.mark_welcome_seen() to authenticated;
grant execute on function public.mark_popup_seen(uuid) to authenticated;

